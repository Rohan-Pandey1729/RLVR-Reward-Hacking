"""Build all paper figures and the numbers.tex macro file from the raw results.

Primary statistics are recomputed here in float64 from the stored per-prompt masses, so
they are free of the 1e-8 floor used in the online logging, and are reported as *drifts*
from each run's own base model:

    rho     = (1/N) sum_x pi(H(x)|x) / [pi(H(x)|x) + pi(gold(x)|x)]      per-prompt hack fraction
    Lambda  = (1/N) sum_x log pi(H(x)|x) - log pi(gold(x)|x)             per-prompt log-odds
    d_rho, d_Lambda = final - base

Proposition 1 makes d_rho and d_Lambda exactly zero for KL-regularised / multiplicative
updates, so they measure departure from the filter baseline and are immune to any residual
mismatch in the base model across conditions.
"""
