def num(k, v):
    # a signed zero ("-0.000", "+0.000") is a rounding artefact; print it unsigned
    if isinstance(v, str) and v[:1] in "+-" and v[1:] and set(v[1:]) <= set("0."):
        v = v[1:]
    NUM[k] = v
    return v


def sci(x, digits=1):
    """LaTeX scientific notation that works for every exponent."""
    if x == 0:
        return "$0$"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10 ** e
    if abs(m - 1.0) < 5e-2:
        return rf"$10^{{{e}}}$"
    return rf"${m:.{digits}f}\times 10^{{{e}}}$"


