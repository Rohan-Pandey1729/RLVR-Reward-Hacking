def stats(entry):
    """(rho, Lambda) in float64 from a metric record carrying per-prompt masses."""
    if "per_prompt_gold" not in entry:
        return entry["mean_hack_frac"], entry["mean_log_odds"]
    g = np.asarray(entry["per_prompt_gold"], dtype=np.float64)
    h = np.asarray(entry["per_prompt_hack"], dtype=np.float64)
    rho = float(np.mean(h / (h + g + FLOOR)))
    raw = np.log(h + FLOOR) - np.log(g + FLOOR)
    CENSOR.append(float(np.mean(np.abs(raw) > LAM_CLIP)))
    lam = float(np.mean(np.clip(raw, -LAM_CLIP, LAM_CLIP)))
    return rho, lam


def flipped_frac(rec, which, thresh=0.5):
    """Fraction of prompts whose final per-prompt hack fraction exceeds `thresh`."""
    e = rec[which][-1]
    if "per_prompt_gold" not in e:
        return float("nan")
    g = np.asarray(e["per_prompt_gold"], float); h = np.asarray(e["per_prompt_hack"], float)
    return float(np.mean(h / (h + g + FLOOR) > thresh))


def val(rec, which, key):
    """key in {rho, lam, d_rho, d_lam, acc, lky, base_rho, base_lam}"""
    if key == "acc":
        return rec[which][-1]["acc"]
    if key == "lky":
        return rec[which][-1]["leaky_reward"]
    br, bl = stats(rec["base"])
    if key == "base_rho":
        return br
    if key == "base_lam":
        return bl
    if key == "flip":
        return flipped_frac(rec, which)
    fr, fl = stats(rec[which][-1])
    return {"rho": fr, "lam": fl, "d_rho": fr - br, "d_lam": fl - bl}[key]


REWARD_TOL = 1e-3


def best_by_reward(rows, cellkeys, which, tol=REWARD_TOL):
    """{cell: {seed: record}} selecting, per cell and seed, the learning rate a practitioner
    would pick: the one maximising the VERIFIER's own reward, which is the only signal
    available without ground truth.

    Verifier reward saturates at 1 for several learning rates, and among those the outcomes
    differ enormously (a run can reach reward 1.000 with zero true accuracy). We therefore
    take the SMALLEST learning rate whose final verifier reward is within `tol` of the best.
    This tie-break is conservative with respect to our hypothesis: smaller steps mean less
    drift away from the filter baseline, so it can only weaken the reported effect."""
    lrkey = "lr_neural" if which == "neural" else "lr_tabular"
    groups = defaultdict(list)
    for r in rows:
        c = r["config"]
        groups[(tuple(c[k] for k in cellkeys), c["seed"])].append(r)
    out = defaultdict(dict)
    for (cell, seed), rs in groups.items():
        top = max(x[which][-1]["leaky_reward"] for x in rs)
        near = [x for x in rs if x[which][-1]["leaky_reward"] >= top - tol]
        out[cell][seed] = min(near, key=lambda x: x["config"][lrkey])
    return out


def series(bycell, which, key, xindex=0):
    xs, mus, sems = [], [], []
    for cell in sorted(bycell, key=lambda c: c[xindex]):
        vals = [val(rec, which, key) for rec in bycell[cell].values()]
        xs.append(cell[xindex]); mus.append(np.mean(vals))
        sems.append(np.std(vals, ddof=1) / np.sqrt(len(vals)) if len(vals) > 1 else 0.0)
    return np.array(xs, float), np.array(mus), np.array(sems)


def seed_values(bycell, which, key, xindex=0):
    """The per-seed values behind series(): one array per cell, in the same order."""
    return [np.array([val(rec, which, key) for rec in bycell[cell].values()])
            for cell in sorted(bycell, key=lambda c: c[xindex])]


def lr_label(lr):
    return f"{lr:g}" if lr >= 0.1 else f"{lr:.0e}".replace("e-0", "e-")


def slope_per_doubling(x_m, y):
    lx = np.log2(x_m)
    A = np.vstack([lx, np.ones_like(lx)]).T
    coef, *_ = np.linalg.lstsq(A, y, rcond=None)
    return float(coef[0])


def crossing(x, y, level=0.0):
    for i in range(1, len(x)):
        if (y[i - 1] - level) <= 0 <= (y[i] - level):
            t = (level - y[i - 1]) / (y[i] - y[i - 1] + 1e-12)
            return float(x[i - 1] + t * (x[i] - x[i - 1]))
    return None


def fmt_cross(c):
    return f"$u={c:.2f}$" if c is not None else "not within the swept range"


def bootci(v, n=10000, seed=0):
    v = np.asarray(v, dtype=float)
    if len(v) < 2:
        return (float("nan"), float("nan"))
    bs = np.random.default_rng(seed).choice(v, size=(n, len(v)), replace=True).mean(1)
    return float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def ci_str(c):
    return f"[{c[0]:+.3f}, {c[1]:+.3f}]"


def select_run(runs, arm, tol=REWARD_TOL):
    """The paper's operating rule applied to a dict of stored runs: the smallest learning
    rate whose final verifier reward is within `tol` of the best, for the given arm."""
    lrkey = "lr_neural" if arm == "neural" else "lr_tabular"
    top = max(r[arm][-1]["leaky_reward"] for r in runs.values())
    near = [r for r in runs.values() if r[arm][-1]["leaky_reward"] >= top - tol]
    return min(near, key=lambda r: r[lrkey])


def sweep_panel(ax, arms, N, key="d_rho", dy=0.035, offsets=(-0.14, 0.14)):
    """A universality sweep: every seed as a dot, the mean over seeds on top, one series per arm.
    `arms` is a list of (selection, arm, colour, marker, label)."""
    if key == "d_rho":
        ax.axhline(0, **BASELINE)
    for (by, which, col, mk, lab), off in zip(arms, offsets):
        x, mu, se = series(by, which, key)
        lx = np.log2(x / N) + off
        for xi, v in zip(lx, seed_values(by, which, key)):
            seed_dots(ax, xi, v, col, dy=dy, dx=0.075, s=5)
        mean_line(ax, lx, mu, col, mk, label=lab, yerr=se)
    u_axis(ax)


